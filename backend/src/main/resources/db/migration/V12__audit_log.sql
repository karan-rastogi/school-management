-- General audit trail for privileged/sensitive actions (role changes, QR token regeneration,
-- notice edits/deletes, admin mutations). Attendance changes keep their dedicated
-- attendance_audit_log; this table covers everything else.
--
-- Rows never store personal data: only the acting user's id, a machine action code, the affected
-- entity's id and an optional short, PII-free detail string.
CREATE TABLE audit_log (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_user_id BIGINT,
    action        VARCHAR(80) NOT NULL,
    entity_type   VARCHAR(60) NOT NULL,
    entity_id     VARCHAR(80),
    details       VARCHAR(500),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_user_id)
        REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_log_occurred_at ON audit_log (occurred_at DESC);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_actor ON audit_log (actor_user_id);
CREATE INDEX idx_audit_log_action ON audit_log (action);

CREATE TABLE notices (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255) NOT NULL,
    body           TEXT         NOT NULL,
    scope          VARCHAR(20)  NOT NULL,
    class_id       BIGINT,
    sender_user_id BIGINT       NOT NULL,
    sender_label   VARCHAR(100) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    edited_at      TIMESTAMPTZ,
    expires_at     TIMESTAMPTZ,
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT fk_notices_class FOREIGN KEY (class_id)
        REFERENCES classes (id) ON DELETE CASCADE,
    CONSTRAINT fk_notices_sender FOREIGN KEY (sender_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_notices_scope CHECK (scope IN ('GLOBAL', 'CLASS')),
    CONSTRAINT ck_notices_scope_class CHECK ((scope = 'CLASS') = (class_id IS NOT NULL))
);

CREATE INDEX idx_notices_scope_class ON notices (scope, class_id);
CREATE INDEX idx_notices_created_at ON notices (created_at DESC);
CREATE INDEX idx_notices_sender ON notices (sender_user_id);
CREATE INDEX idx_notices_expires_at ON notices (expires_at);

CREATE TABLE otp_codes (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone      VARCHAR(32)  NOT NULL,
    code_hash  VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_otp_codes_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_otp_codes_phone_created_at ON otp_codes (phone, created_at DESC);
CREATE INDEX idx_otp_codes_expires_at ON otp_codes (expires_at);

CREATE TABLE teacher_assignments (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_user_id  BIGINT       NOT NULL,
    class_id         BIGINT       NOT NULL,
    subject_name     VARCHAR(100) NOT NULL,
    is_class_teacher BOOLEAN      NOT NULL DEFAULT FALSE,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_teacher_assignments_teacher FOREIGN KEY (teacher_user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_teacher_assignments_class FOREIGN KEY (class_id)
        REFERENCES classes (id) ON DELETE CASCADE,
    CONSTRAINT uq_teacher_assignments_subject UNIQUE (teacher_user_id, class_id, subject_name)
);

CREATE INDEX idx_teacher_assignments_class ON teacher_assignments (class_id);
CREATE INDEX idx_teacher_assignments_teacher ON teacher_assignments (teacher_user_id);

CREATE UNIQUE INDEX uq_teacher_assignments_class_teacher
    ON teacher_assignments (class_id)
    WHERE is_class_teacher AND active;

CREATE TABLE school_calendar (
    date        DATE         PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL,
    description VARCHAR(500),
    CONSTRAINT ck_school_calendar_type CHECK (type IN ('WORKING', 'HOLIDAY', 'HALF_DAY', 'EXAM'))
);

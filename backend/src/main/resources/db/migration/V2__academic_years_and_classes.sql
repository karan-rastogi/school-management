CREATE TABLE academic_years (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    is_current BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_academic_years_name UNIQUE (name),
    CONSTRAINT ck_academic_years_dates CHECK (end_date > start_date)
);

CREATE UNIQUE INDEX uq_academic_years_single_current
    ON academic_years (is_current)
    WHERE is_current;

CREATE TABLE classes (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    section          VARCHAR(20)  NOT NULL,
    academic_year_id BIGINT       NOT NULL,
    CONSTRAINT fk_classes_academic_year FOREIGN KEY (academic_year_id)
        REFERENCES academic_years (id) ON DELETE RESTRICT,
    CONSTRAINT uq_classes_name_section_year UNIQUE (name, section, academic_year_id)
);

CREATE INDEX idx_classes_academic_year ON classes (academic_year_id);

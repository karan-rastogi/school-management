CREATE TABLE attendance (
    id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT     NOT NULL,
    date      DATE        NOT NULL,
    status    VARCHAR(20) NOT NULL,
    source    VARCHAR(20) NOT NULL,
    marked_by BIGINT      NOT NULL,
    marked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_attendance_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_marked_by FOREIGN KEY (marked_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_attendance_student_date UNIQUE (student_id, date),
    CONSTRAINT ck_attendance_status CHECK (status IN ('PRESENT', 'ABSENT', 'LATE', 'HALF_DAY', 'EXCUSED')),
    CONSTRAINT ck_attendance_source CHECK (source IN ('QR', 'MANUAL', 'PAPER_BACKFILL'))
);

CREATE INDEX idx_attendance_date ON attendance (date);
CREATE INDEX idx_attendance_marked_by ON attendance (marked_by);

CREATE TABLE attendance_audit_log (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT      NOT NULL,
    changed_by    BIGINT      NOT NULL,
    changed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    old_status    VARCHAR(20),
    new_status    VARCHAR(20) NOT NULL,
    reason        VARCHAR(500),
    CONSTRAINT fk_attendance_audit_log_attendance FOREIGN KEY (attendance_id)
        REFERENCES attendance (id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_audit_log_changed_by FOREIGN KEY (changed_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_attendance_audit_log_old_status CHECK (
        old_status IS NULL OR old_status IN ('PRESENT', 'ABSENT', 'LATE', 'HALF_DAY', 'EXCUSED')),
    CONSTRAINT ck_attendance_audit_log_new_status CHECK (
        new_status IN ('PRESENT', 'ABSENT', 'LATE', 'HALF_DAY', 'EXCUSED'))
);

CREATE INDEX idx_attendance_audit_log_attendance ON attendance_audit_log (attendance_id, changed_at DESC);
CREATE INDEX idx_attendance_audit_log_changed_by ON attendance_audit_log (changed_by);

CREATE TABLE attendance_queries (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id           BIGINT      NOT NULL,
    attendance_date      DATE        NOT NULL,
    raised_by_user_id    BIGINT      NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    response             TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_by_user_id BIGINT,
    responded_at         TIMESTAMPTZ,
    CONSTRAINT fk_attendance_queries_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_queries_raised_by FOREIGN KEY (raised_by_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_queries_responded_by FOREIGN KEY (responded_by_user_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_attendance_queries_status CHECK (status IN ('OPEN', 'RESOLVED'))
);

CREATE INDEX idx_attendance_queries_student_date ON attendance_queries (student_id, attendance_date);
CREATE INDEX idx_attendance_queries_status ON attendance_queries (status);
CREATE INDEX idx_attendance_queries_raised_by ON attendance_queries (raised_by_user_id);

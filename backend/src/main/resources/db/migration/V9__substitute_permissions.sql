CREATE TABLE substitute_permissions (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_user_id    BIGINT      NOT NULL,
    class_id           BIGINT      NOT NULL,
    granted_by_user_id BIGINT      NOT NULL,
    granted_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_from         DATE        NOT NULL,
    valid_until        DATE        NOT NULL,
    reason             VARCHAR(500),
    CONSTRAINT fk_substitute_permissions_teacher FOREIGN KEY (teacher_user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_substitute_permissions_class FOREIGN KEY (class_id)
        REFERENCES classes (id) ON DELETE CASCADE,
    CONSTRAINT fk_substitute_permissions_granted_by FOREIGN KEY (granted_by_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_substitute_permissions_window CHECK (valid_until >= valid_from)
);

CREATE INDEX idx_substitute_permissions_lookup
    ON substitute_permissions (teacher_user_id, class_id, valid_from, valid_until);

CREATE TABLE students (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(255) NOT NULL,
    admission_no   VARCHAR(50)  NOT NULL,
    dob            DATE         NOT NULL,
    photo_path     VARCHAR(512),
    qr_token       UUID         NOT NULL DEFAULT gen_random_uuid(),
    admission_date DATE         NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_students_admission_no UNIQUE (admission_no),
    CONSTRAINT uq_students_qr_token UNIQUE (qr_token),
    CONSTRAINT ck_students_status CHECK (status IN ('ACTIVE', 'LEFT')),
    CONSTRAINT ck_students_dates CHECK (dob <= admission_date)
);

CREATE INDEX idx_students_full_name ON students (full_name);
CREATE INDEX idx_students_status ON students (status);

CREATE TABLE student_enrollments (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT      NOT NULL,
    class_id   BIGINT      NOT NULL,
    roll_no    INTEGER,
    from_date  DATE        NOT NULL,
    to_date    DATE,
    CONSTRAINT fk_student_enrollments_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_enrollments_class FOREIGN KEY (class_id)
        REFERENCES classes (id) ON DELETE RESTRICT,
    CONSTRAINT uq_student_enrollments_student_from UNIQUE (student_id, from_date),
    CONSTRAINT ck_student_enrollments_dates CHECK (to_date IS NULL OR to_date >= from_date),
    CONSTRAINT ck_student_enrollments_roll_no CHECK (roll_no IS NULL OR roll_no > 0)
);

CREATE INDEX idx_student_enrollments_class ON student_enrollments (class_id);

CREATE TABLE parent_student_links (
    parent_user_id BIGINT      NOT NULL,
    student_id     BIGINT      NOT NULL,
    relationship   VARCHAR(50),
    CONSTRAINT pk_parent_student_links PRIMARY KEY (parent_user_id, student_id),
    CONSTRAINT fk_parent_student_links_parent FOREIGN KEY (parent_user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_parent_student_links_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE
);

CREATE INDEX idx_parent_student_links_student ON parent_student_links (student_id);
